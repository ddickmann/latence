#: The pinned Redaction stack: ``redaction.hybrid_rule`` with an EMPTY config on purpose. Omitting
#: ``detectors`` selects the comprehensive built-in set, so the published number is the number an
#: adopter gets by default. Narrowing the default would show up here as a recall drop.
REDACTION_STACK_PIN = StackPin(stage="redaction", provider="redaction.hybrid_rule", config={})


@dataclass(frozen=True)
class GoldSpan:
    """One planted PII value and its exact location in the document text."""

    pii_type: str
    value: str
    start: int
    end: int


@dataclass(frozen=True)
class GoldDocument:
    """One synthetic document plus every PII value planted in it (possibly none)."""

    doc_id: str
    language: str
    sensitivity: str
    text: str
    pii: tuple[GoldSpan, ...]


def load_corpus(root: Path) -> tuple[GoldDocument, ...]:
    """Read and validate the shipped synthetic PII corpus.

    Validation is not ceremony: it re-checks ``text[start:end] == value`` for every planted
    span, so a corpus edited without regenerating its offsets is refused rather than scored.
    """
    path = root / CORPUS_FILE
    if not path.is_file():
        msg = f"Synthetic PII corpus {path} is missing from the installed package."
        raise BenchmarkDataError(msg)
    documents: list[GoldDocument] = []
    for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), start=1):
        if not line.strip():
            continue
        source = f"{CORPUS_FILE}:{number}"
        try:
            row: Any = json.loads(line)
        except json.JSONDecodeError as exc:
            msg = f"{source}: not valid JSON ({exc.msg})."
            raise BenchmarkDataError(msg) from exc
        text = str(row["text"])
        spans: list[GoldSpan] = []
        for raw in row["pii"]:
            span = GoldSpan(
                pii_type=str(raw["pii_type"]),
                value=str(raw["value"]),
                start=int(raw["start"]),
                end=int(raw["end"]),
            )
            if text[span.start : span.end] != span.value:
                msg = (
                    f"{source}: gold span [{span.start}, {span.end}) slices "
                    f"{text[span.start : span.end]!r} but the annotation says {span.value!r}. "
                    "Regenerate the corpus with latence_benchmark.corpora.build_synthetic_pii "
                    "rather than editing offsets by hand."
                )
                raise BenchmarkDataError(msg)
            spans.append(span)
        documents.append(
            GoldDocument(
                doc_id=str(row["doc_id"]),
                language=str(row["language"]),
                sensitivity=str(row["sensitivity"]),
                text=text,
                pii=tuple(spans),
            )
        )
    if not documents:
        msg = f"{CORPUS_FILE} is empty; there is nothing to score."
        raise BenchmarkDataError(msg)
    return tuple(documents)


#: A detected span, as ``(document, pii_type, start, end)``.
_Detected = tuple[str, str, int, int]
#: A gold span, as ``(document, pii_type, start, end)``.
_Gold = tuple[str, str, int, int]


def _covers(detected: _Detected, gold: _Gold) -> bool:
    """Whether ``detected`` masks the whole of ``gold`` (same document, containing span)."""
    return detected[0] == gold[0] and detected[2] <= gold[2] and detected[3] >= gold[3]


def _alignment(gold: Sequence[_Gold], detected: Sequence[_Detected]) -> int:
    """Size of a maximum one-to-one pairing of gold values to detections that contain them.

    Kuhn's augmenting-path algorithm, run per document (``_covers`` can only hold within one
    document, so the matching decomposes and recursion stays bounded by the detections in a
    single document). Iteration follows input order throughout, so the result is deterministic;
    the *size* of a maximum matching is in any case independent of the order chosen.
    """
    by_document: dict[str, list[int]] = {}
    for index, span in enumerate(detected):
        by_document.setdefault(span[0], []).append(index)

    claimed_by: dict[int, int] = {}

    def augment(gold_index: int, visited: set[int]) -> bool:
        item = gold[gold_index]
        for detected_index in by_document.get(item[0], ()):
            if detected_index in visited or not _covers(detected[detected_index], item):
                continue
            visited.add(detected_index)
            holder = claimed_by.get(detected_index)
            if holder is None or augment(holder, visited):
                claimed_by[detected_index] = gold_index
                return True
        return False

    return sum(augment(gold_index, set()) for gold_index in range(len(gold)))


def coverage(
    dimension: str,
    name: str,
    *,
    gold: Sequence[_Gold],
    detected: Sequence[_Detected],
) -> MetricScore:
    """Score containment rather than boundary equality — the privacy question.

    A gold value is a true positive when a detected span contains it, and boundary disagreement
    costs nothing: masking ``[8, 25)`` where the value sits at ``[10, 21)`` still masked the
    value, which is what a privacy claim is about.

    The credit is nevertheless **one detection per value**. Both halves of the score are counted
    over the same alignment — true positives are matched pairs, false negatives are gold values
    left unmatched, false positives are detections left unmatched — which is precisely the
    multiset rule :func:`~latence_benchmark.metrics.confusion` applies, with containment
    substituted for boundary equality.

    Counting covered *gold values* against unmatched *detected spans* instead would mix two
    measurement bases, and the gap is not academic: one span over the whole document would be
    credited for every value it swallowed while being charged nothing, so a redactor that masks
    the entire corpus — destroying all of its utility — would outrank a real one on this,
    the published headline. Over-redaction is the largest failure mode of a redactor, and a
    metric that cannot see it is not measuring redaction. Under the alignment it is charged in
    full: the mask-everything detector claims one value per document and answers for every
    other detection it emitted.
    """
    matched = _alignment(gold, detected)
    return MetricScore(
        dimension=dimension,
        name=name,
        true_positives=matched,
        false_positives=len(detected) - matched,
        false_negatives=len(gold) - matched,
    )


@dataclass(frozen=True)
class RedactionSuite:
    """Benchmarks the Redaction Stage's recall on the shipped synthetic PII corpus."""

    name: str = "redaction"
    stage: str = "redaction"
    dataset: DatasetSpec = SYNTHETIC_PII
    stack_pin: StackPin = REDACTION_STACK_PIN

    def run(self, root: Path, *, limit: int | None = None) -> SuiteResult:
        redactor: PIIDetector = load_provider(
            self.stack_pin,
            capability=CapabilityKind.REDACTION,
            protocol=PIIDetector,
        )
        documents = load_corpus(root)
        languages = tuple(dict.fromkeys(document.language for document in documents))

        gold: list[_Gold] = []
        detected: list[_Detected] = []
        by_language: dict[str, tuple[list[_Gold], list[_Detected]]] = {
            language: ([], []) for language in languages
        }
        documents_scored = 0
        for language in languages:
            slice_ = [d for d in documents if d.language == language]
            if limit is not None:
                slice_ = slice_[:limit]
            documents_scored += len(slice_)
            chunks = [
                as_chunk(
                    document.doc_id,
                    document.text,
                    language=document.language,
                    sensitivity=document.sensitivity,
                )
                for document in slice_
            ]
            for document in slice_:
                for span in document.pii:
                    item = (document.doc_id, span.pii_type, span.start, span.end)
                    gold.append(item)
                    by_language[language][0].append(item)
            for chunk in redactor.redact(chunks):
                for span_out in chunk.pii_spans:
                    found = (
                        chunk.document_record_id,
                        span_out.pii_type,
                        span_out.char_start,
                        span_out.char_end,
                    )
                    detected.append(found)
                    by_language[language][1].append(found)

        per_language = [
            coverage("language", language, gold=g, detected=d)
            for language, (g, d) in by_language.items()
        ]
        # The union, NOT just the gold types: `pii_type` is a partition dimension, so
        # `results._metric_tables` renders a bold **MICRO** aggregate over these slices. Slicing
        # only over the gold inventory would give a detection labelled with a type the gold set
        # never names no slice to belong to — it would vanish from the table instead of being
        # charged, and the published aggregate would report a precision the run did not earn.
        # Rule-based defaults happen to stay inside the inventory; a re-pin (`gliner_pii` emits
        # URL, DATE_TIME, LOCATION, NRP...) does not.
        scored_types = sorted({item[1] for item in gold} | {item[1] for item in detected})
        per_type = [
            coverage(
                "pii_type",
                pii_type,
                gold=[g for g in gold if g[1] == pii_type],
                detected=[d for d in detected if d[1] == pii_type],
            )
            for pii_type in scored_types
        ]
        untyped_gold = [(g[0], "", g[2], g[3]) for g in gold]
        untyped_detected = [(d[0], "", d[2], d[3]) for d in detected]
        criteria = [
            micro(per_language, dimension="match", name="coverage (value fully masked)"),
            confusion("match", "exact span", gold=untyped_gold, predicted=untyped_detected),
            confusion("match", "exact span+type", gold=gold, predicted=detected),
        ]

        notes = [
            "Scored with Provider 'redaction.hybrid_rule' at its DEFAULT config: no `detectors` "
            "key, which selects the comprehensive built-in recogniser set. Narrowing that "
            "default would show up here as a recall drop.",
            "The corpus is SYNTHETIC — no real personal data is in this repository. Every value "
            "is a reserved or published example (see the DatasetSpec license notes).",
            "The gold set deliberately includes person names and postal addresses, which a "
            "rule-based redactor structurally cannot detect. The recall below is therefore NOT "
            "expected to be 1.0, and the per-type table shows exactly where the residual is. "
            "The learned re-pin for names is `--provider redaction.gliner_pii`.",
            "OVER-redaction is charged, not only under-redaction: `coverage` credits ONE "
            "detection per gold value (a maximum one-to-one alignment under containment), so a "
            "Provider cannot buy recall by widening its masks — every span it emits that is not "
            "matched to a value is a false positive. Masking everything and masking nothing are "
            "both visible failures here.",
            "Per-type slices count a detected span as a false positive for its own type when it "
            "covers no gold value; a value masked under a different label counts as a miss for "
            "its gold type (and appears under the `exact span+type` criterion), because a "
            "type-scoped redaction policy would not have covered it.",
        ]
        if limit is not None:
            notes.append(
                f"SUBSET RUN — capped at {limit} document(s) per language. NOT comparable with "
                "full-corpus results."
            )
        return SuiteResult(
            suite=self.name,
            stage=self.stage,
            dataset=self.dataset,
            stack_pin=self.stack_pin,
            splits=(),
            documents_scored=documents_scored,
            metrics=(*per_language, *per_type, *criteria),
            headline_dimension="language",
            notes=tuple(notes),
        )
