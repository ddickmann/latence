"""The Redaction suite — publishing the number the privacy claim rests on.

The framework's central privacy claim is that the Redaction Stage masks the PII in a corpus.
Until it is measured on data anyone can inspect, that claim is a promise. This suite turns it
into evidence: a synthetic, fully-inspectable PII corpus, the real ``redaction.hybrid_rule``
Provider at its default (comprehensive) config, and a published recall.

**No real PII, ever.** The corpus ships inside this package
(:mod:`latence_benchmark.corpora`) and every value in it is a documented, reserved example:
``example.com``/``example.de`` domains (RFC 2606), ``555``-prefixed NANP numbers (reserved for
fiction), the ``4111 1111 1111 1111`` test card, ``192.0.2.0/24`` and ``203.0.113.0/24``
(RFC 5737 TEST-NET), the published example IBANs, AWS's own ``AKIAIOSFODNN7EXAMPLE`` docs key,
and obviously-fictional names (``Erika Mustermann``, ``John Q. Public``). It is generated by
:mod:`latence_benchmark.corpora.build_synthetic_pii` — offsets are computed from the templates,
never hand-written, and a test regenerates the file and asserts byte-equality, so the shipped
corpus cannot drift from its own auditable source.

**The corpus is built to be failable.** It plants person names and postal addresses, which a
rule-based redactor structurally cannot catch, alongside the structured types it can. A gold set
containing only what the pinned Provider already detects would report 100% recall forever and
detect no regression in either direction — the classic tautological benchmark. Three clean
control documents with no PII at all supply the precision half.

Three match criteria are reported, and the headline is deliberately the loosest of them:

* **coverage** — is the gold value *entirely inside* some masked span? That, and not exact
  boundary agreement, is the question a privacy claim actually answers, and it is the headline.
* **exact span** — same boundaries.
* **exact span + type** — same boundaries and the same PII label. A value masked under the wrong
  label is still masked, but a type-scoped policy (``types: ["ssn"]``) would have missed it, so
  the gap between this and coverage is a real operational risk and is published as such.
"""

