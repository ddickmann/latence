"""The ontology's constraints in SHACL and its provenance in PROV-O, beside the Turtle file
(ticket 42; the destination's check 3: open-standard exports validate).

- **SHACL** (``ontology.shacl.ttl``): one ``sh:NodeShape`` per concept that is not a value set,
  targeting the concept's class (the same IRI as in ``ontology.ttl``). Each attribute is a
  property shape with its datatype and at most one value; a personal column's shape says
  ``sh:maxCount 0`` (no value of it is in what the estate exports); each relation is a property
  shape with the class of its end (``skos:Concept`` for a value set) and, where the relation is
  many-to-one, at most one value. **What a person has not yet approved is written and
  deactivated** (``sh:deactivated true``, ``v:reviewStatus "proposed"``): a consumer that
  validates data against the file is held only to what is stated or approved.
- **PROV-O** (``ontology.prov.ttl``): every concept, relation and measure is a ``prov:Entity``
  generated by the build (a ``prov:Activity``) and attributed to the engine (a
  ``prov:SoftwareAgent``); each decision a person made on one is an activity of its own,
  associated with that person (a ``prov:Person``) and influencing the element; an element read
  from the catalog is derived from the catalog object it was read from.

Identifiers are the Turtle file's: an element's IRI is the same in all three files. The same
export gives the same text.
"""

from __future__ import annotations

import hashlib
from typing import Any

from .turtle import _lit, _status, _Writer, _xsd

SH = "@prefix sh: <http://www.w3.org/ns/shacl#> .\n"
PROV = "@prefix prov: <http://www.w3.org/ns/prov#> .\n"


def _active(status: str) -> list[tuple[str, str]]:
    return [
        ("v:reviewStatus", _lit(status)),
        *([("sh:deactivated", "true")] if status == "proposed" else []),
    ]


def to_shacl(export: dict[str, Any], base: str) -> str:
    w = _Writer(base)
    w.lines[0] += SH
    schemes = {c["id"] for c in export["concepts"] if c["kind"] == "reference"}
    relations: dict[str, list[dict[str, Any]]] = {}
    for r in export["relations"]:
        if r["from"] not in schemes:
            relations.setdefault(r["from"], []).append(r)
    for c in export["concepts"]:
        if c["id"] in schemes:
            continue
        cls, status = w.iri(c["id"]), _status(c)
        props = []
        for a in c.get("attributes") or []:
            path = w.iri(f"{c['id']}#{a['column']}")
            if a.get("sensitive"):
                props.append(
                    f"[ sh:path {path} ; sh:maxCount 0 ; rdfs:comment "
                    f"{_lit('personal or masked: no value of it is exported')} ]"
                )
            else:
                props.append(f"[ sh:path {path} ; sh:datatype {_xsd(a['type'])} ; sh:maxCount 1 ]")
        for r in relations.get(c["id"], []):
            end = "skos:Concept" if r["to"] in schemes else w.iri(r["to"])
            r_status = _status(r)
            body = [
                f"sh:path {w.iri(r['id'])}",
                f"sh:class {end}",
                f"v:reviewStatus {_lit(r_status)}",
            ]
            if r.get("cardinality") == "many_to_one":
                body.append("sh:maxCount 1")
            if r_status == "proposed":
                body.append("sh:deactivated true")
            props.append("[ " + " ; ".join(body) + " ]")
        w.add(
            "e:s" + hashlib.sha1(c["id"].encode("utf-8")).hexdigest()[:14],
            [
                ("a", "sh:NodeShape"),
                ("sh:targetClass", cls),
                ("rdfs:label", _lit(c["label"])),
                *_active(status),
                *[("sh:property", p) for p in props],
            ],
        )
    return "\n".join(w.lines)


def to_prov(export: dict[str, Any], base: str) -> str:
    w = _Writer(base)
    w.lines[0] += PROV
    meta = export["meta"]
    build, engine = "e:build", "e:engine"
    w.add(engine, [("a", "prov:SoftwareAgent"), ("rdfs:label", _lit("the ontology builder"))])
    w.add(
        build,
        [
            ("a", "prov:Activity"),
            ("rdfs:label", _lit(f"the build of the estate {meta['source']}")),
            ("prov:wasAssociatedWith", engine),
        ],
    )
    people: dict[str, str] = {}
    for kind, part in (
        ("concept", export["concepts"]),
        ("relation", export["relations"]),
        ("measure", export["measures"]),
    ):
        for el in part:
            iri = w.iri(el["id"])
            pairs = [
                ("a", "prov:Entity"),
                ("rdfs:label", _lit(el.get("label") or el["id"])),
                ("prov:wasGeneratedBy", build),
                ("prov:wasAttributedTo", engine),
            ]
            if kind == "concept" and el.get("object"):
                obj = "e:o" + hashlib.sha1(str(el["object"]).encode("utf-8")).hexdigest()[:14]
                w.add(
                    obj,
                    [
                        ("a", "prov:Entity"),
                        ("rdfs:label", _lit(el.get("object_name") or el["object"])),
                    ],
                )
                pairs.append(("prov:wasDerivedFrom", obj))
            decision = el.get("decision") or {}
            if decision.get("by") and decision.get("by") != "engine":
                person = people.setdefault(
                    str(decision["by"]),
                    "e:p" + hashlib.sha1(str(decision["by"]).encode("utf-8")).hexdigest()[:14],
                )
                act = (
                    "e:d" + hashlib.sha1(f"{el['id']}|{el.get('claim')}".encode()).hexdigest()[:14]
                )
                w.add(
                    act,
                    [
                        ("a", "prov:Activity"),
                        ("rdfs:label", _lit(f"{decision['verdict']} by {decision['by']}")),
                        ("prov:wasAssociatedWith", person),
                    ],
                )
                pairs.append(("prov:wasInfluencedBy", act))
            w.add(iri, pairs)
    for name, person in sorted(people.items()):
        w.add(person, [("a", "prov:Person"), ("rdfs:label", _lit(name))])
    return "\n".join(w.lines)
